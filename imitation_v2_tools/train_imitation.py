"""Pure offline replay imitation trainer; no PPO, self-play or update_000271.

Requires validated NPZ shards generated by build_replicar_dataset.py.
Action head predicts an 8-frame sequence; value head predicts imminent goal side.
Value head is NOT an action-value or a proven rollout planner.
"""
from __future__ import annotations
import argparse, json, math, os, random
from pathlib import Path
import numpy as np


def create_model(in_dim=84,hidden=560,horizon=8):
    import torch
    from torch import nn
    class ImitationModel(nn.Module):
        def __init__(self):
            super().__init__()
            self.encoder=nn.GRU(input_size=in_dim,hidden_size=hidden,num_layers=2,batch_first=True)
            self.policy=nn.Sequential(nn.LayerNorm(hidden),nn.Linear(hidden,384),nn.GELU(),
                                      nn.Linear(384,horizon*8))
            self.value=nn.Sequential(nn.LayerNorm(hidden),nn.Linear(hidden,256),nn.GELU(),nn.Linear(256,3))
        def forward(self,x):
            h=self.encoder(x)[0][:,-1]
            return self.policy(h).reshape(-1,horizon,8),self.value(h)
    return ImitationModel()


def loss_metrics(policy,value,y,v):
    import torch
    import torch.nn.functional as F
    # Analog controls: Huber; binary jump/boost/handbrake: BCE logits.
    analog=F.smooth_l1_loss(policy[:,:,:5].tanh(),y[:,:,:5])
    binary=F.binary_cross_entropy_with_logits(policy[:,:,5:],y[:,:,5:])
    value_ce=F.cross_entropy(value,v)
    total=analog+binary+0.25*value_ce
    binary_accuracy=((policy[:,:,5:]>0).eq(y[:,:,5:]>0.5)).float().mean()
    analog_mae=(policy[:,:,:5].tanh()-y[:,:,:5]).abs().mean()
    val_acc=(value.argmax(dim=1)==v).float().mean()
    return total,{'analog_loss':analog.item(),'button_bce':binary.item(),
                  'value_ce':value_ce.item(),'analog_mae':analog_mae.item(),
                  'button_accuracy':binary_accuracy.item(),'value_accuracy':val_acc.item()}


def read_shards(root,split):
    files=sorted((root/split).glob('*.npz'))
    if not files:raise RuntimeError(f'No {split} NPZ shards under {root / split}. Stop rather than evaluate on training data.')
    return files


def iterator(shards,batch,seed,shuffle):
    rng=np.random.default_rng(seed)
    order=list(shards)
    if shuffle:rng.shuffle(order)
    for file in order:
        with np.load(file,allow_pickle=False) as z:
            x,y,v=z['x'],z['y'],z['v']
        if x.ndim!=3 or x.shape[-1]!=84 or y.shape!=(len(x),8,8) or len(v)!=len(x):
            raise ValueError(f'Incorrect shard shapes in {file}')
        if not len(x) or not np.isfinite(x).all() or not np.isfinite(y).all():
            raise ValueError(f'Invalid finite data in {file}')
        inds=np.arange(len(x))
        if shuffle:rng.shuffle(inds)
        for start in range(0,len(inds),batch):
            sl=inds[start:start+batch]
            yield x[sl],y[sl],v[sl]


def evaluate(model,files,batch,device):
    import torch
    model.eval();accum={};total=0
    with torch.no_grad():
        for x,y,v in iterator(files,batch,0,False):
            x=torch.from_numpy(x).to(device)
            y=torch.from_numpy(y).to(device)
            v=torch.from_numpy(v).long().to(device)
            pred,value=model(x)
            loss,metrics=loss_metrics(pred,value,y,v)
            metrics['loss']=loss.item()
            n=len(x);total+=n
            for k,val in metrics.items():accum[k]=accum.get(k,0.)+val*n
    return {k:val/total for k,val in accum.items()}


def atomic_checkpoint(file,model,optimizer,epoch,best,config):
    import torch
    file.parent.mkdir(parents=True,exist_ok=True)
    part=file.with_suffix('.tmp')
    torch.save({'model':model.state_dict(),'optimizer':optimizer.state_dict(),
                'epoch':epoch,'best_val':best,'config':config},part)
    part.replace(file)


def main():
    p=argparse.ArgumentParser()
    p.add_argument('--data',type=Path,default=Path('data/imitation_npz'))
    p.add_argument('--output',type=Path,default=Path('runs/replay_imitation_fresh'))
    p.add_argument('--epochs',type=int,default=20)
    p.add_argument('--batch-size',type=int,default=256)
    p.add_argument('--lr',type=float,default=2e-4)
    p.add_argument('--seed',type=int,default=2026) # random seed only; NEVER weights from 271
    p.add_argument('--device',default='auto',choices=('auto','cpu','cuda'))
    p.add_argument('--wandb-mode',default='offline',choices=('disabled','offline','online'))
    p.add_argument('--wandb-project',default='rl-imitation-fresh')
    p.add_argument('--resume',action='store_true')
    a=p.parse_args()
    if a.epochs<1 or a.batch_size<1 or a.lr<=0:p.error('Invalid training settings')
    import torch
    from imitation_metrics import ImitationMetrics
    random.seed(a.seed);np.random.seed(a.seed);torch.manual_seed(a.seed)
    if torch.cuda.is_available():torch.cuda.manual_seed_all(a.seed)
    torch.set_num_threads(min(8,max(1,os.cpu_count() or 1)))
    device='cuda' if a.device=='auto' and torch.cuda.is_available() else 'cpu' if a.device=='auto' else a.device
    train_files=read_shards(a.data,'train');val_files=read_shards(a.data,'val')
    # Test split is intentionally not used to select hyperparameters.
    train_stems={p.stem for p in train_files};val_stems={p.stem for p in val_files}
    if train_stems & val_stems:raise ValueError('Replay appears in both train and validation!')
    split_groups={'duels':[],'doubles':[]}
    manifest_path=a.data/'manifest.json'
    if manifest_path.exists():
        entries=json.loads(manifest_path.read_text(encoding='utf8'))
        lookup={e['sha256']:e.get('players') for e in entries if e.get('status')=='ok'}
        for file in val_files:
            if lookup.get(file.stem)==2:split_groups['duels'].append(file)
            if lookup.get(file.stem)==4:split_groups['doubles'].append(file)
        train_modes={lookup.get(file.stem) for file in train_files}
        for mode,group in ((2,'duels'),(4,'doubles')):
            if mode in train_modes and not split_groups[group]:
                raise RuntimeError(f'Training has {group} but validation has none. Fix match-level split before training.')
    model=create_model().to(device)
    opt=torch.optim.AdamW(model.parameters(),lr=a.lr,weight_decay=0.01)
    param_count=sum(p.numel() for p in model.parameters())
    print('Pure BC, trainable parameters:',param_count,'device:',device,'train shards:',len(train_files),'val shards:',len(val_files))
    start=1;best=math.inf
    chk=a.output/'latest.pt'
    if a.resume:
        if not chk.exists():p.error('--resume checkpoint missing')
        saved=torch.load(chk,map_location=device,weights_only=False)
        model.load_state_dict(saved['model']);opt.load_state_dict(saved['optimizer'])
        start=int(saved['epoch'])+1;best=float(saved['best_val'])
    elif chk.exists():
        p.error('Run directory already has a checkpoint: choose a new --output or --resume')
    config={'data':str(a.data),'train_shards':len(train_files),'val_shards':len(val_files),
            'params':param_count,'batch':a.batch_size,'lr':a.lr,'seed':a.seed,
            'history':8,'chunk':8,'policy':'8 analog/binary controls',
            'value_target':'goal-for/against within 10s; not Q-value',
            'training':'offline supervised only'}
    a.output.mkdir(parents=True,exist_ok=True)
    (a.output/'config.json').write_text(json.dumps(config,indent=2))
    with ImitationMetrics(a.output,project=a.wandb_project,wandb_mode=a.wandb_mode,config=config) as m:
        for epoch in range(start,a.epochs+1):
            model.train();samples=0;running=0.
            for x,y,v in iterator(train_files,a.batch_size,a.seed+epoch,True):
                x=torch.from_numpy(x).to(device)
                y=torch.from_numpy(y).to(device)
                v=torch.from_numpy(v).long().to(device)
                pred,value=model(x)
                loss,_=loss_metrics(pred,value,y,v)
                opt.zero_grad(set_to_none=True)
                loss.backward()
                torch.nn.utils.clip_grad_norm_(model.parameters(),1.)
                opt.step()
                samples+=len(x);running+=loss.item()*len(x)
            val=evaluate(model,val_files,a.batch_size,device)
            metrics={'train/loss':running/samples,**{'val/'+k:v for k,v in val.items()},
                     'train/samples':samples,'val/shards':len(val_files)}
            for mode,files in split_groups.items():
                if files:
                    mode_metrics=evaluate(model,files,a.batch_size,device)
                    metrics.update({f'val_{mode}/'+k:v for k,v in mode_metrics.items()})
            m.log(epoch,metrics)
            if val['loss']<best:
                best=val['loss']
                atomic_checkpoint(a.output/'best.pt',model,opt,epoch,best,config)
            atomic_checkpoint(chk,model,opt,epoch,best,config)
            print('epoch',epoch,'train',round(running/samples,4),'val',round(val['loss'],4),'val buttons',round(val['button_accuracy'],3),'best',round(best,4),flush=True)
    print('Training finished. This does NOT establish in-game improvement. Run held-out match evaluations before deployment.')

if __name__=='__main__':main()
